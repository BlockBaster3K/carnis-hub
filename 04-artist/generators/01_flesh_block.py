#!/usr/bin/env python3
"""
flesh_block.py — Живая плоть (Carnis: Adaptive Hivemind)  ·  v3

Метод: «плоская масса + ручные штампы».
Базовая ткань — один тон (как в ванильных текстурах: большие спокойные
зоны). Поверх — небольшое число ОРГАНИЧЕСКИХ ФОРМ, каждая нарисована
руками как пиксельный штамп (список смещений) и поставлена вручную:
  · 4 тёмных кластера-провала (гнёзда между мышцами)
  · 1 светлый мышечный гребень по диагонали (3 штампа-волокна)
  · 3 поры-ямки
  · 1 прожилка с развилкой (ручная ломаная)
  · 3 влажные точки
Крупные плоские зоны + редкие связные формы = ткань, а не шум.

Запуск:  python3 flesh_block.py   →   flesh_block.png
Зависимости: Pillow
"""

from PIL import Image

SIZE = 16

# ── Палитра ────────────────────────────────────────────────────────
PAL = {
    'd': (58, 26, 24),    # #3A1A18 — провал
    's': (74, 34, 32),    # #4A2220 — тень
    'a': (90, 43, 40),    # #5A2B28 — основной тон
    'b': (102, 51, 47),   # #66332F — переход к свету
    'c': (112, 56, 51),   # #703833 — гребень волокна
    'v': (124, 66, 66),   # #7C4242 — прожилка
    'w': (138, 80, 80),   # #8A5050 — влажный блик
}

# ── Штампы (нарисованы руками; (dx, dy, tone)) ─────────────────────
# Провал A — вытянутый по горизонтали
BLOB_A = [(-1, 0, 's'), (0, 0, 's'), (1, 0, 's'), (2, 0, 's'),
          (0, 1, 'd'), (1, 1, 'd'), (2, 1, 's'),
          (1, 2, 's')]
# Провал B — компактный вертикальный
BLOB_B = [(0, -1, 's'), (-1, 0, 's'), (0, 0, 'd'), (1, 0, 's'),
          (0, 1, 'd'), (0, 2, 's')]
# Провал C — косой клин
BLOB_C = [(0, 0, 's'), (1, 0, 's'), (1, 1, 'd'), (2, 1, 's'),
          (2, 2, 's')]
# Гребень-волокно (светлая диагональ, 2 px толщиной, рваная)
RIDGE_A = [(0, 0, 'c'), (1, 0, 'b'), (1, 1, 'c'), (2, 1, 'b'),
           (2, 2, 'c'), (3, 2, 'b')]
RIDGE_B = [(0, 0, 'b'), (0, 1, 'c'), (1, 1, 'b'), (1, 2, 'c'),
           (2, 2, 'b')]
# Мягкая светлая облачность (разбивает плоскость, без контраста)
CLOUD = [(0, 0, 'b'), (1, 0, 'b'), (0, 1, 'b'), (1, 1, 'b'), (2, 1, 'b'),
         (1, 2, 'b'), (2, 2, 'b'), (3, 2, 'b'), (2, 3, 'b'), (3, 3, 'b')]
# Поры
PORE = [(0, 0, 'd'), (0, 1, 's'), (1, 1, 's'), (-1, 0, 's')]

# ── Размещение (вручную; координаты завершаются по модулю 16) ──────
BLOB_A_AT = [(2, 11), (12, 3), (9, 14)]
BLOB_B_AT = [(5, 2), (14, 8)]
BLOB_C_AT = [(0, 6), (7, 6)]
CLOUD_AT = [(3, 3), (11, 10), (13, 13)]
RIDGE_A_AT = [(1, 12), (6, 9), (11, 6)]     # главный гребень: низ-лево → верх-право
RIDGE_B_AT = [(4, 15), (9, 11), (14, 7)]    # его продолжение/второе волокно
PORE_AT = [(8, 1), (3, 8), (12, 15)]

# ── Прожилка (ручная ломаная) + развилка, влажные точки ────────────
VEIN = [(0, 3), (1, 3), (2, 4), (3, 4), (3, 5), (4, 5), (5, 6), (6, 6),
        (7, 7), (8, 7), (8, 8), (9, 8), (10, 8), (11, 9), (12, 9),
        (13, 10), (14, 10), (15, 11)]
VEIN_BRANCH = [(8, 8), (9, 9), (10, 9), (10, 10), (11, 11), (12, 11)]
VEIN_WET = [(4, 5), (9, 8), (12, 9)]


def place(buf, stamp, ox, oy):
    for dx, dy, t in stamp:
        buf[(oy + dy) % SIZE][(ox + dx) % SIZE] = PAL[t]


def paint():
    # 1) плоская масса
    buf = [[PAL['a']] * SIZE for _ in range(SIZE)]

    # 2) мягкая светлая облачность (кладётся первой, чтобы провалы легли поверх)
    for (x, y) in CLOUD_AT:
        place(buf, CLOUD, x, y)

    # 3) тёмные провалы
    for (x, y) in BLOB_A_AT:
        place(buf, BLOB_A, x, y)
    for (x, y) in BLOB_B_AT:
        place(buf, BLOB_B, x, y)
    for (x, y) in BLOB_C_AT:
        place(buf, BLOB_C, x, y)

    # 4) мышечный гребень
    for (x, y) in RIDGE_A_AT:
        place(buf, RIDGE_A, x, y)
    for (x, y) in RIDGE_B_AT:
        place(buf, RIDGE_B, x, y)

    # 5) поры (ямка + тень сверху)
    for (x, y) in PORE_AT:
        place(buf, PORE, x, y)

    # 6) прожилка
    for (x, y) in VEIN + VEIN_BRANCH:
        buf[y % SIZE][x % SIZE] = PAL['v']
    for (x, y) in VEIN_WET:
        buf[y % SIZE][x % SIZE] = PAL['w']

    return buf


def to_image(buf):
    img = Image.new('RGBA', (SIZE, SIZE))
    for y in range(SIZE):
        for x in range(SIZE):
            img.putpixel((x, y), buf[y][x] + (255,))
    return img


if __name__ == "__main__":
    to_image(paint()).save("flesh_block.png")
    print("flesh_block.png written (16×16)")
