#!/usr/bin/env python3
from pathlib import Path
import json,zipfile
ROOT=Path(__file__).resolve().parents[1]
items=json.loads((ROOT/'deliverables/tz2_metrics.json').read_text(encoding='utf-8'))
header='''# Carnis · ТЗ-2 · варианты текстур

**Художник · версия 3.4.2 · статус: подготовлено, визуальная приёмка не пройдена полностью.**

В списке ТЗ фактически **21** новый файл: 3 + 8 + 3 + 4 + 3; «19» в заголовке — арифметическая ошибка. Базовые PNG ТЗ-1 сохранены без изменений. `flesh_veins` — плоская текстура, отдельных торцов нет.

## Состав и запуск

PNG: `src/main/resources/assets/carnis/textures/block/<имя>.png`. Для каждого есть полный автономный `deliverables/scripts/<имя>.py`, нужен только Python 3 и Pillow:

```bash
python3 deliverables/scripts/flesh_block_1.py src/main/resources/assets/carnis/textures/block/flesh_block_1.png
```

Скрипт без аргумента пишет PNG в текущий каталог. Каждый скрипт содержит готовую 16×16 карту цветов; никакого random. Точные имена, отличия и метрики приведены ниже. Интерактивная контрольная стена: `deliverables/preview_ТЗ-2.html`; общий PNG: `deliverables/Стены_ТЗ-2.png`.

## Проверки

* 21/21: 16×16, RGBA, alpha=255; каждый автономный скрипт перерисовывает PNG пиксель-в-пиксель.
* Палитра каждого варианта равна множеству цветов фактически используемой базовой PNG, включая цвета бликов. После проверки некоторые тона семейства заменены ближайшим тоном базы; недостающие тона добавлены в отдельные пиксели. **Исключение из ограничения «5–8»: базовая `flesh_veins_t3.png` содержит 9 цветов, и оба её варианта тоже 9.** Одновременно выполнить буквальное равенство и ограничение в 8 невозможно без изменения базы.
* Точное совпадение с базой после поворота, отражения или циклического сдвига проверено: 0 из 21. Это проверка точных преобразований, а не доказательство художественной оригинальности.
* Seam h/v ниже 2.0 по локальному `tools/carnis_px.py`: яркость Y=0.299R+0.587G+0.114B, средний перепад на стыке / средний горизонтальный перепад по всем пикселям, **включая горизонтальное замыкание**. Обе оси делятся на этот же горизонтальный знаменатель; числа округлены до 2 знаков. Метрика касается самоповтора одного тайла, не гарантирует незаметности стыков разных вариантов. `flesh_veins_t4_1` близок к порогу — повторно проверить в игре.
* Стены 4×4 смешивают базу с вариантами по вручную заданным фиксированным раскладкам. Рандомный выбор в Minecraft и blockstate-модели не реализованы и не проверялись; стены не заменяют испытание нескольких случайных раскладок в игре.

## Оставшиеся замечания к приёмке

* В стене `nerve_pillar_top` заметны концентрические «глаза», в `refractory_flesh` — квадратные мотивы; на `stomach_pool_side` и `sinew_spikes` сохраняется направленная полосатость. Местами вклад вносит и принятая базовая текстура. Эти семейства не заявляются прошедшими критерий отсутствия повторов.
* Формальный автоматический анализ мотива >3 px и контраста >20% не проведён; заметные крупные контрастные структуры есть, в частности на нервных торцах. Следовательно соответствие этому критерию не подтверждено и для торцов визуально не выполнено.
* Цель «невозможно найти два одинаковых блока» буквально недостижима: 16 позиций и только 4 текстуры `flesh_block`; повтор текстур неизбежен. Оценивать можно только заметность повтора.
* Изменение уже принятой базы для исправления общей стены не включено в поставку; доработка отмеченных семейств требует пересмотра сочетания базы и вариантов.

## Все варианты

Колонка «Seam» — h / v. Все пути PNG имеют общий префикс `src/main/resources/assets/carnis/textures/block/`, пути скриптов — `deliverables/scripts/`.

| PNG | Скрипт | Отличие от базы | Seam h/v | Цветов |
|---|---|---|---:|---:|
'''
for o in items:
 name=o['name'];desc=o['description'].replace('|','/').replace('\n',' ')
 header+=f"| `{name}.png` | `{name}.py` | {desc} | {o['seam'][0]:.2f} / {o['seam'][1]:.2f} | {o['colors']} |\n"
header+='''
## Воспроизведение и границы поставки

`python3 generators/export_tz2.py` пересобирает 21 скрипт и PNG, сверяя цвета с базовыми PNG. `python3 generators/verify_tz2.py` повторяет технические проверки. `python3 generators/wall_tz2.py` строит стены из фактически сохранённых PNG. Модели GeckoLib и предметы не начинались.
'''
report=ROOT/'deliverables/REPORT_ТЗ-2.md';report.write_text(header,encoding='utf-8')
archive=ROOT/'deliverables/Carnis_ТЗ-2.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
 for item in items:
  n=item['name'];
  for p in (ROOT/'deliverables/scripts'/f'{n}.py',ROOT/'src/main/resources/assets/carnis/textures/block'/f'{n}.png'): z.write(p,p.relative_to(ROOT))
 for p in [report,ROOT/'deliverables/preview_ТЗ-2.html',ROOT/'deliverables/Стены_ТЗ-2.png',ROOT/'deliverables/tz2_metrics.json']:
  z.write(p,p.relative_to(ROOT))
print('Wrote',report,archive)
