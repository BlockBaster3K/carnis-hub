package com.carnis.mod.client.renderer;

/**
 * Красная вспышка урона для GeckoLib-мобов (дефект N2).
 *
 * <p>Почему отдельный класс, а не три строки в каждом рендерере. Нас интересует
 * ровно один вызов, и он должен быть <b>побайтово одинаковым</b> во всех
 * четырёх рендерерах: если разъедется, то разъедется незаметно — у одного моба
 * вспышка ярче, у другого слабее, и никто не поймёт почему. Один метод — одно
 * место правки.
 *
 * <p>Почему не overlay. Штатный путь GeckoLib для вспышки — {@code
 * getPackedOverlay}: он ставит {@code hurt} в overlay-координаты вершин, а
 * ванильный шейдер по ним подмешивает красный. В этой связке (мод собран на
 * GeckoLib 4.4.4, у тестера 4.8.4) путь формально цел — {@code
 * GeoEntityRenderer.getPackedOverlay} есть и в 4.4.4, и в 4.8.4, и overlay
 * доходит до {@code createVerticesOfQuad} без подмены, — но в игре вспышки нет.
 * Перепроверять чужую библиотеку по исходникам дальше нельзя: результат
 * «должно работать» уже получен один раз и оказался неверным.
 *
 * <p>Поэтому вспышка рисуется там, где мод полностью управляет результатом, —
 * в цвете вершин ({@code getRenderColor} → {@code buffer.vertex(..., red,
 * green, blue, alpha)}). Этот множитель применяется к текстуре на любом
 * {@code RenderType} и не зависит ни от overlay-координат, ни от версии
 * GeckoLib.
 *
 * <p>Интенсивность. В ванилле вспышка — это подмешивание красного поверх
 * текстуры; чем сильнее затемняем G и B, тем краснее модель. Берём
 * {@code GREEN = BLUE = 0.42}: тёмно-красная плоть остаётся различимой (не
 * превращается в сплошное пятно), а событие читается однозначно. При
 * {@code hurtTime == 0} возвращается чистый белый — обычный вид.
 */
final class HurtFlash {
    /** Множитель зелёного и синего каналов во время вспышки. */
    private static final float TINT = 0.42F;

    private HurtFlash() {
    }

    /**
     * Цвет рендера с учётом вспышки урона.
     *
     * @param hurtTime тики с момента последнего урона ({@code > 0} — бьют)
     * @param deathTime тики с момента смерти ({@code > 0} — добивают)
     * @return белый в покое, красный множитель во время вспышки
     */
    static software.bernie.geckolib.core.object.Color of(int hurtTime, int deathTime) {
        if (hurtTime <= 0 && deathTime <= 0) {
            return software.bernie.geckolib.core.object.Color.WHITE;
        }
        return software.bernie.geckolib.core.object.Color.ofRGB(1.0F, TINT, TINT);
    }
}
