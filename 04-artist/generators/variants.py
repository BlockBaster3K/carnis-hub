def canvas(t='a'):
    return [[t] * S for _ in range(S)]


def clump(g, x, y, w, h, tone):
    for yy in range(h):
        for xx in range(w):
            g[(y + yy) % S][(x + xx) % S] = tone


def dot(g, pts, tone):
    for x, y in pts:
        g[y % S][x % S] = tone


def poly(g, pts, tone):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(steps + 1):
            x = round(x0 + (x1 - x0) * i / steps)
            y = round(y0 + (y1 - y0) * i / steps)
            g[y % S][x % S] = tone


def band(g, pts, tone, w=2):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(steps + 1):
            x = round(x0 + (x1 - x0) * i / steps)
            y = round(y0 + (y1 - y0) * i / steps)
            g[y % S][x % S] = tone
            if w >= 2:
                g[(y + 1) % S][x % S] = tone


def rows(g):
    return [''.join(r) for r in g]


