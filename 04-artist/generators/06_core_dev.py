#!/usr/bin/env python3
"""Dev v6: ручная карта пятнами разного масштаба (не диагональный ритм).
База '3'; три крупных световых лоскута '4'; трещины '2' ветвями Y;
две ямки '1'; редкие гребни '5'; влага '6'; жила 'v' с развилкой."""
import sys
sys.path.insert(0, '/home/user/carnis/tools')
from carnis_px import to_image, seam_sheet, seam_metric
from PIL import Image

S = 16
RAM = {
    '1': (62, 26, 23),    # провал
    '2': (76, 35, 33),    # тень/трещина
    '3': (90, 43, 40),    # база
    '4': (99, 48, 44),    # световой лоскут
    '5': (110, 55, 50),   # гребень
    '6': (132, 76, 74),   # влага
    'v': (120, 62, 60),   # жила
    'V': (140, 84, 82),   # жила светлая
}

PATCH = {
    '4': [(1, 1), (2, 1), (3, 1), (4, 1), (1, 2), (2, 2), (3, 2), (4, 2),
          (5, 2), (2, 3), (3, 3), (4, 3), (5, 3), (2, 4), (3, 4), (1, 3),
          # правый лоскут
          (9, 6), (10, 6), (11, 6), (9, 7), (10, 7), (11, 7), (12, 7),
          (10, 8), (11, 8), (12, 8), (11, 9), (12, 9), (12, 10), (13, 10),
          # нижне-левый
          (1, 11), (2, 11), (1, 12), (2, 12), (3, 12), (2, 13), (3, 13),
          (3, 14), (4, 13), (4, 14),
          # одиночный мягкий у правого края
          (14, 14), (15, 14), (14, 15)],
}
CRACKS = {
    '2': [(7, 0), (7, 1), (6, 2), (6, 3), (6, 4), (5, 5), (5, 6), (4, 7),
          (4, 8), (3, 9), (3, 10),
          (6, 3), (7, 4), (8, 4), (9, 5),
          (12, 12), (11, 13), (10, 13), (9, 14), (8, 15),
          (14, 3), (15, 4), (14, 5),
          (0, 6), (1, 6)],
    '1': [(6, 3), (4, 8), (11, 13)],
    '5': [(2, 2), (3, 3), (10, 7), (2, 12), (13, 9), (8, 11)],
    '6': [(4, 2), (11, 8), (2, 12), (15, 14)],
}
VEIN = [(0, 8), (1, 8), (2, 9), (3, 9), (4, 9), (5, 10), (6, 10), (7, 10),
        (8, 10), (9, 10), (10, 11), (11, 11), (12, 11), (13, 11),
        (14, 12), (15, 12)]
FORK = [(7, 10), (7, 9), (8, 8), (9, 7)]
VLIT = [(2, 9), (8, 10), (13, 11)]


def paint():
    g = [['3'] * S for _ in range(S)]
    for tone, pts in PATCH.items():
        for x, y in pts:
            g[y][x] = tone
    for tone, pts in CRACKS.items():
        for x, y in pts:
            g[y][x] = tone
    for x, y in VEIN + FORK:
        g[y][x] = 'v'
    for x, y in VLIT:
        g[y][x] = 'V'
    return g


def report(name, g):
    rgb = [[RAM[c] for c in row] for row in g]
    to_image(rgb).resize((96, 96), Image.NEAREST).save(f"/home/user/carnis/previews/v6_{name}.png")
    seam_sheet(rgb).resize((288, 288), Image.NEAREST).save(f"/home/user/carnis/previews/v6seam_{name}.png")
    print(name, "seam:", seam_metric(rgb))
    return rgb


if __name__ == "__main__":
    g = paint()
    report('flesh_block', g)
    # текстовый дамп для наглядности
    for row in g:
        print(''.join(row))
