package com.carnis.mod.datagen;

import com.carnis.mod.CarnisMod;
import com.google.common.hash.Hashing;
import net.minecraft.data.CachedOutput;
import net.minecraft.data.DataProvider;
import net.minecraft.data.PackOutput;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackType;
import net.minecraftforge.common.data.ExistingFileHelper;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CompletableFuture;

/** Deterministic, hand-pixelled 32x32 sprites generated by Forge DataGen. */
public final class OrganicItemTextureProvider implements DataProvider {
    private static final int SIZE = 32;
    private static final ExistingFileHelper.ResourceType TEXTURE_TYPE =
            new ExistingFileHelper.ResourceType(PackType.CLIENT_RESOURCES, ".png", "textures");
    private static final List<Texture> TEXTURES = List.of(
            new Texture("item", "viral_dart", Art.VIRAL),
            new Texture("item", "purification_dart", Art.PURIFICATION),
            new Texture("item", "neural_binding_matrix", Art.MATRIX),
            new Texture("item", "creeping_tendrils", Art.TENDRILS),
            new Texture("block", "creeping_tendrils", Art.TENDRILS));

    private final PackOutput.PathProvider itemPaths;
    private final PackOutput.PathProvider blockPaths;

    public OrganicItemTextureProvider(PackOutput output, ExistingFileHelper existingFiles) {
        itemPaths = output.createPathProvider(PackOutput.Target.RESOURCE_PACK, "textures/item");
        blockPaths = output.createPathProvider(PackOutput.Target.RESOURCE_PACK, "textures/block");
        for (Texture texture : TEXTURES) {
            existingFiles.trackGenerated(new ResourceLocation(CarnisMod.MOD_ID,
                    texture.folder() + "/" + texture.name()), TEXTURE_TYPE);
        }
    }

    @Override
    public CompletableFuture<?> run(CachedOutput cache) {
        try {
            for (Texture texture : TEXTURES) {
                BufferedImage image = switch (texture.art()) {
                    case VIRAL -> dart(false);
                    case PURIFICATION -> dart(true);
                    case MATRIX -> matrix();
                    case TENDRILS -> tendrils();
                };
                ByteArrayOutputStream buffer = new ByteArrayOutputStream();
                if (!ImageIO.write(image, "png", buffer)) throw new IOException("PNG writer unavailable");
                byte[] bytes = buffer.toByteArray();
                PackOutput.PathProvider paths = texture.folder().equals("item") ? itemPaths : blockPaths;
                Path path = paths.file(new ResourceLocation(CarnisMod.MOD_ID, texture.name()), "png");
                cache.writeIfNeeded(path, bytes, Hashing.sha256().hashBytes(bytes));
            }
            return CompletableFuture.completedFuture(null);
        } catch (IOException exception) {
            return CompletableFuture.failedFuture(exception);
        }
    }

    @Override
    public String getName() { return "Carnis procedural darts, matrix and tendrils"; }

    private static BufferedImage canvas() {
        return new BufferedImage(SIZE, SIZE, BufferedImage.TYPE_INT_ARGB);
    }

    // The syringes point toward the upper right. Layering is deliberately pixel-aligned.
    private static BufferedImage dart(boolean clean) {
        BufferedImage image = canvas();
        int outline = clean ? 0xFF25303A : 0xFF372314;
        int shadow = clean ? 0xFF536875 : 0xFF79501F;
        int metal = clean ? 0xFF91A9B1 : 0xFFC09239;
        int shine = clean ? 0xFFDCE9E8 : 0xFFF5D778;
        int glass = clean ? 0xFF30545C : 0xFF532E35;
        int fluid = clean ? 0xFF48D1CC : 0xFFB81135;
        int bright = clean ? 0xFFAAFFED : 0xFFFF5260;
        // Butt, casing and two reinforcing collars.
        line(image, 5, 26, 22, 9, 4, outline);
        line(image, 5, 25, 21, 9, 3, shadow);
        line(image, 6, 24, 21, 9, 2, metal);
        line(image, 7, 23, 20, 10, 0, shine);
        line(image, 3, 25, 7, 29, 1, outline);
        line(image, 3, 24, 7, 28, 0, metal);
        line(image, 7, 19, 12, 24, 1, outline);
        line(image, 8, 19, 12, 23, 0, shine);
        line(image, 17, 9, 22, 14, 1, outline);
        line(image, 18, 9, 22, 13, 0, shine);
        // Framed glass chamber with luminous serum and specular glints.
        line(image, 11, 19, 17, 13, 2, glass);
        line(image, 11, 19, 17, 13, 1, fluid);
        line(image, 12, 17, 16, 13, 0, bright);
        pixel(image, 13, 18, clean ? 0xFF76F2E3 : 0xFFFF8990);
        pixel(image, 16, 15, 0xFFF3FFFF);
        // Needle socket, fine shaft and point.
        line(image, 21, 9, 24, 6, 1, outline);
        line(image, 22, 8, 24, 6, 0, metal);
        line(image, 24, 6, 29, 1, 0, 0xFFC8DADE);
        pixel(image, 29, 1, 0xFFF5FFFF);
        return image;
    }

    private static BufferedImage matrix() {
        BufferedImage image = canvas();
        // Layered circular silhouette and directional shading.
        disc(image, 16, 16, 13, 0xFF1B1018);
        disc(image, 16, 16, 12, 0xFF351923);
        disc(image, 15, 15, 10, 0xFF54202B);
        disc(image, 13, 12, 6, 0xFF692633);
        line(image, 7, 19, 12, 23, 0, 0xFF1C111A);
        line(image, 12, 23, 20, 24, 0, 0xFF1C111A);
        line(image, 20, 24, 25, 18, 0, 0xFF1C111A);
        // Organic branching, nodes and hot centres.
        line(image, 8, 11, 14, 15, 0, 0xFF9F293D);
        line(image, 14, 15, 20, 10, 0, 0xFF9F293D);
        line(image, 14, 15, 20, 21, 0, 0xFF8C2238);
        line(image, 14, 15, 10, 22, 0, 0xFF8C2238);
        node(image, 8, 11); node(image, 14, 15); node(image, 20, 10);
        node(image, 20, 21); node(image, 10, 22); node(image, 24, 15);
        // A conductive grid of orthogonal traces, clipped to the core silhouette.
        trace(image, 6, 13, 10, 13); trace(image, 10, 13, 10, 8);
        trace(image, 10, 8, 18, 8); trace(image, 18, 8, 18, 12);
        trace(image, 18, 12, 25, 12); trace(image, 25, 12, 25, 18);
        trace(image, 7, 18, 12, 18); trace(image, 12, 18, 12, 24);
        trace(image, 12, 24, 20, 24); trace(image, 20, 24, 20, 19);
        trace(image, 20, 19, 26, 19); trace(image, 16, 6, 16, 10);
        trace(image, 16, 10, 14, 10); trace(image, 6, 16, 9, 16);
        trace(image, 22, 14, 22, 17); trace(image, 22, 17, 18, 17);
        stud(image, 10, 13); stud(image, 18, 12); stud(image, 12, 18);
        stud(image, 20, 19); stud(image, 22, 17); stud(image, 16, 10);
        return image;
    }

    private static BufferedImage tendrils() {
        BufferedImage image = canvas();
        // Thick maroon roots split into grasping, tapered fingers.
        line(image, 16, 31, 16, 22, 3, 0xFF3C0A1A);
        line(image, 16, 25, 9, 18, 2, 0xFF3C0A1A);
        line(image, 9, 18, 7, 10, 2, 0xFF3C0A1A);
        line(image, 7, 10, 3, 6, 1, 0xFF3C0A1A);
        line(image, 16, 24, 23, 17, 2, 0xFF3C0A1A);
        line(image, 23, 17, 25, 8, 2, 0xFF3C0A1A);
        line(image, 25, 8, 29, 4, 1, 0xFF3C0A1A);
        line(image, 16, 22, 15, 10, 2, 0xFF3C0A1A);
        line(image, 15, 10, 19, 3, 1, 0xFF3C0A1A);
        line(image, 15, 31, 15, 22, 1, 0xFF862740);
        line(image, 15, 24, 8, 17, 1, 0xFF862740);
        line(image, 8, 17, 6, 10, 0, 0xFFBC4C5F);
        line(image, 17, 23, 23, 16, 1, 0xFF862740);
        line(image, 23, 16, 25, 8, 0, 0xFFBC4C5F);
        line(image, 15, 21, 14, 10, 1, 0xFF862740);
        line(image, 14, 10, 18, 3, 0, 0xFFBC4C5F);
        // Two-pixel cup rims and dark centres, all inside opaque sinew.
        cup(image, 15, 28); cup(image, 12, 21); cup(image, 8, 14);
        cup(image, 18, 21); cup(image, 22, 16); cup(image, 24, 11);
        cup(image, 15, 18); cup(image, 15, 13); cup(image, 17, 7);
        return image;
    }

    private static void node(BufferedImage image, int x, int y) {
        disc(image, x, y, 2, 0xFF8A1C30);
        pixel(image, x, y, 0xFFEC4B52);
        pixel(image, x - 1, y - 1, 0xFFFF9790);
    }

    private static void stud(BufferedImage image, int x, int y) {
        pixel(image, x, y, 0xFFFFE8A0);
        pixel(image, x + 1, y, 0xFFB67A21);
    }

    private static void cup(BufferedImage image, int x, int y) {
        pixel(image, x, y, 0xFFDA7882);
        pixel(image, x + 1, y, 0xFF590C22);
    }

    private static void trace(BufferedImage image, int x1, int y1, int x2, int y2) {
        line(image, x1, y1, x2, y2, 0, 0xFFD49A38);
    }

    private static void disc(BufferedImage image, int cx, int cy, int radius, int color) {
        for (int y = -radius; y <= radius; y++) {
            for (int x = -radius; x <= radius; x++) {
                if (x * x + y * y <= radius * radius) pixel(image, cx + x, cy + y, color);
            }
        }
    }

    private static void line(BufferedImage image, int x0, int y0, int x1, int y1, int width, int color) {
        int dx = Math.abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        int dy = -Math.abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        int error = dx + dy;
        while (true) {
            disc(image, x0, y0, width, color);
            if (x0 == x1 && y0 == y1) break;
            int twice = 2 * error;
            if (twice >= dy) { error += dy; x0 += sx; }
            if (twice <= dx) { error += dx; y0 += sy; }
        }
    }

    private static void pixel(BufferedImage image, int x, int y, int color) {
        if (x >= 0 && y >= 0 && x < SIZE && y < SIZE) image.setRGB(x, y, color);
    }

    private enum Art { VIRAL, PURIFICATION, MATRIX, TENDRILS }
    private record Texture(String folder, String name, Art art) { }
}
